#!/usr/bin/env python3
"""Bake the bots' routes into QuakeC: qwtf/bots_nav.qc (PLAN.md M7).

    scripts/build_nav.py            # regenerate qwtf/bots_nav.qc
    scripts/build_nav.py --check    # exit 0 if the committed file is fresh

M7: "Bots move with the real player hull, follow map_route waypoints, fight,
and run the key." The routes are map_route.py flood fills of maps/forts.map
itself -- the same hull, the same cell rules and the same reader
(scripts/mapfile.py) that tests/test_forts_map.py and the walk suite use -- so
a route that exists here is one the engine lets a player walk, and a change to
the map changes the routes with it.

THE PLAN. The two bots must not share a chokepoint: measured, two symmetric
bots met on the bridge, stopped to fight, and killed each other on the same
spot for the whole smoke while neither ever reached a vault. So the routes are
deliberately ASYMMETRIC -- red is the bridge bot (out over the bridge, home
through the underwater passage with the key), blue lives in the passage (every
run but the first is a swim). They then meet in the channel, which is where
the fights happen, and the winner of a fight either captures or picks the
dropped key up -- either way, somebody captures.

Per team, three routes (red bot shown):
  out_a   spawn room -> enemy key vault        (the first run of a life)
  home    enemy key vault -> own key stand     (the capture run, key in hand)
  out_b   own key stand  -> enemy key vault    (the loop after a capture)

out_a starts at the spawn-room centre because the bot spawns there; out_b
starts at the own stand because a capture ends there, so qwtf/bots.qc picks
whichever of the two starts where the bot is standing. The router's goal cell
is snapped to the walkable grid and always lands within touch range of the key
or the stand (the objective is a 32-unit trigger), so "walk to the last node"
is also "walk into the objective".

The output is a list of QWTF_node('x y z') calls between QWTF_route_begin(id)
and QWTF_route_end(). The nodes are linked into entity chains by qwtf/bots.qc,
which owns the machinery; this file owns only the numbers.
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import map_route as mr  # noqa: E402  (pulls in gen_map + mapfile)

MAP_PATH = os.path.join(ROOT, "maps", "forts.map")
OUT_PATH = os.path.join(ROOT, "qwtf", "bots_nav.qc")

# The routes, by id. 0 red out_a, 1 red home, 2 red out_b,
# 3 blue out_a, 4 blue home, 5 blue out_b. ids are the same numbers
# qwtf/bots.qc uses to pick a route.
RED_OUT_A, RED_HOME, RED_OUT_B = 0, 1, 2
BLUE_OUT_A, BLUE_HOME, BLUE_OUT_B = 3, 4, 5
# The defenders' patrol (owner, 2026-10-10: bots defend; attacking is a later,
# harder skill): spawn -> own key, own key -> own stand, own stand -> own key.
RED_G_SPAWN, RED_G_UP, RED_G_DOWN = 6, 7, 8
BLUE_G_SPAWN, BLUE_G_UP, BLUE_G_DOWN = 9, 10, 11


def join_legs(legs):
    """Concatenate chained legs into one node list, dropping the duplicate
    junction point."""
    pts = []
    for i, leg in enumerate(legs):
        if i:
            leg = leg[1:]          # the junction node ends the previous leg
                                   # and opens this one
        pts.extend(leg)
    return pts


def entities(path):
    """The .map's point entities as dicts. The file is machine-generated by
    gen_map.py with a fixed shape, so the parser stays deliberately small."""
    ents = []
    cur = {}
    with open(path, "r") as f:
        for line in f:
            line = line.strip()
            m = re.match(r'^"(\w+)"\s+"(.*)"$', line)
            if m:
                cur[m.group(1)] = m.group(2)
            elif line == "}":
                if cur:
                    ents.append(cur)
                cur = {}
    return ents


def named(ents, classname, targetname):
    for e in ents:
        if e.get("classname") == classname and e.get("targetname") == targetname:
            return tuple(float(v) for v in e["origin"].split())
    raise SystemExit(f"FATAL: no {classname} named {targetname} in {path}")


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="regenerate to a temp file and compare; no writes")
    ap.add_argument("--map", default="forts2",
                    help="map name in maps/ (default forts2, the live map)")
    args = ap.parse_args(argv)

    # The geometry AND the entities come from the same file: map_route reads
    # its solids from FORTS_MAPFILE, so point it at the chosen map too.
    map_path = os.path.join(ROOT, "maps", args.map + ".map")
    mr.FORTS_MAPFILE = map_path
    ents = entities(map_path)
    key_red = named(ents, "item_qwtf_key", "key_red")
    key_blue = named(ents, "item_qwtf_key", "key_blue")
    stand_red = named(ents, "item_qwtf_stand", "stand_red")
    stand_blue = named(ents, "item_qwtf_stand", "stand_blue")

    spawns = [tuple(float(v) for v in e["origin"].split())
              for e in ents if e.get("classname") == "info_player_deathmatch"]
    mid_x = (key_red[0] + key_blue[0]) / 2
    red_spawns = [p for p in spawns if p[0] < mid_x]
    blue_spawns = [p for p in spawns if p[0] > mid_x]
    if not red_spawns or not blue_spawns:
        raise SystemExit("FATAL: no spawns on one side of the map")

    def centre(points):
        n = len(points)
        return (sum(p[0] for p in points) / n,
                sum(p[1] for p in points) / n,
                sum(p[2] for p in points) / n)

    red_spawn_c = centre(red_spawns)
    blue_spawn_c = centre(blue_spawns)

    bs = mr.boxes("forts")
    water = [b for b in mr.forts_water()]

    def rt(src, dst):
        path, fail, why = mr.route(bs, src, dst, 16, "forts", water)
        if path is None:
            raise SystemExit(f"FATAL: no route for {src} -> {dst}: {why} {fail}")
        return path, mr.thin(path, 40)

    # Each fort's vault-ramp TOP, derived from the routes themselves rather
    # than hardcoded: a route's z mode is the yard/bridge plateau it walks,
    # and scanning back from the goal, the first node back at plateau height
    # is where that route's vault descent began -- the yard end of the ramp.
    def ramp_top(path):
        from collections import Counter
        plateau = Counter(p[2] for p in path).most_common(1)[0][0]
        for p in reversed(mr.thin(path, 40)):
            if p[2] >= plateau - 8:
                return p
        raise SystemExit("FATAL: no vault descent found in the route")

    # The bridge's far end node, out of the blue key's route: the plateau
    # node nearest the map's mid-x. Used as a chain point, because A* on its
    # own would send red's post-capture run down the ramp and through the
    # passage -- the swim is 211 cells against the bridge's 560 -- and red
    # would never cross the bridge at all.
    mid_x = (key_red[0] + key_blue[0]) / 2
    red_out_a_path, red_out_a = rt(red_spawn_c, key_blue)
    ramp_blue = ramp_top(red_out_a_path)
    bridge_end = min(mr.thin(red_out_a_path, 40), key=lambda p: abs(p[0] - mid_x))
    blue_out_probe_path, _ = rt(blue_spawn_c, key_red)
    ramp_red = ramp_top(blue_out_probe_path)

    # The guard routes. Blue's come from the router; red's are blue's MIRRORED
    # about the keys' midpoint, because the router's rise rule can climb in
    # mid-air (it judges a rise by the surface under the next column, not the
    # mover's own height) and red's own spawn -> key route came out walking a
    # level at z 160 that does not exist, then dropping through a wall: the red
    # bot never reached its vault (owner playtest 2026-10-10). The forts are
    # mirror images, so a walkable blue route mirrors to a walkable red one.
    axis = key_red[0] + key_blue[0]
    if abs(key_red[1] - key_blue[1]) > 1 or abs((stand_red[0] + stand_blue[0]) - axis) > 1:
        raise SystemExit("FATAL: the map is not mirrored about the keys' midpoint; "
                         "red guard routes cannot be blue's mirror")

    def mirror(pts):
        return [(axis - p[0], p[1], p[2]) for p in pts]

    # The patrol is spawn -> own vault -> back to spawn. The router's climb
    # from the vault to the roof turn-in is not walkable either (both bots got
    # half way up the stairwell and fell back, at mirrored spots), so the roof
    # is left out until the router's rise rule is fixed; "UP" walks blue's
    # working spawn -> vault route backwards, and "DOWN" is that route again.
    blue_g_spawn = rt(blue_spawn_c, key_blue)[1]
    blue_g_up = list(reversed(blue_g_spawn))
    blue_g_down = blue_g_spawn

    routes = [
        (RED_OUT_A, red_out_a,
         "spawn room -> blue key, over the bridge"),
        (RED_HOME, rt(key_blue, stand_red)[1],
         "blue key -> red stand, the swim home"),
        (RED_OUT_B, join_legs([rt(stand_red, ramp_red)[1],
                               rt(ramp_red, bridge_end)[1],
                               rt(bridge_end, key_blue)[1]]),
         "red stand -> blue key, over the bridge again"),
        (BLUE_OUT_A, rt(blue_spawn_c, stand_blue)[1],
         "spawn room -> own stand, down into the vault"),
        (BLUE_HOME, rt(key_red, stand_blue)[1],
         "red key -> blue stand, the swim home"),
        (BLUE_OUT_B, rt(stand_blue, key_red)[1],
         "blue stand -> red key, the swim out"),
        (BLUE_G_SPAWN, blue_g_spawn, "guard: blue spawn -> blue key"),
        (BLUE_G_UP, blue_g_up, "guard: blue key -> blue spawn"),
        (BLUE_G_DOWN, blue_g_down, "guard: blue spawn -> blue key (again)"),
        (RED_G_SPAWN, mirror(blue_g_spawn), "guard: red spawn -> red key (blue's, mirrored)"),
        (RED_G_UP, mirror(blue_g_up), "guard: red key -> red spawn (blue's, mirrored)"),
        (RED_G_DOWN, mirror(blue_g_down), "guard: red spawn -> red key again (blue's, mirrored)"),
    ]

    lines = []
    lines.append("// qwtf/bots_nav.qc -- GENERATED by scripts/build_nav.py from")
    lines.append(f"// maps/{args.map}.map. DO NOT EDIT: rerun scripts/build_nav.py --map {args.map}.")
    lines.append("//")
    lines.append("// PLAN.md M7: the bots' routes. Each route is a map_route.py flood")
    lines.append("// fill of the map the qbsp compiles, on the real player hull, thinned")
    lines.append("// to its corners. A route here is a route the engine lets a player")
    lines.append("// walk; if the map changes, this file changes with it (the check_all")
    lines.append("// 'nav' row fails until scripts/build_nav.py is rerun).")
    lines.append("//")
    lines.append("// The two routes sets are deliberately ASYMMETRIC -- red crosses the")
    lines.append("// bridge, blue swims the passage -- because two symmetric bots met on")
    lines.append("// the bridge and killed each other there for a whole smoke run while")
    lines.append("// nobody reached a vault. See the PLAN comment in scripts/build_nav.py.")
    lines.append("//")
    lines.append("// Route ids (qwtf/bots.qc picks by them):")
    for rid, pts, what in routes:
        lines.append(f"//   {rid}  {what} ({len(pts)} nodes)")
    lines.append("#ifdef __QW__")
    lines.append("void() QWTF_nav_build =")
    lines.append("{")

    for rid, pts, what in routes:
        lines.append(f"    // {what}: {len(pts)} nodes")
        lines.append(f"    QWTF_route_begin({rid});")
        for p in pts:
            lines.append(f"    QWTF_node('{p[0]:.0f} {p[1]:.0f} {p[2]:.0f}');")
        lines.append(f"    QWTF_route_end('{p[0]:.0f} {p[1]:.0f} {p[2]:.0f}');")
    lines.append("};")
    lines.append("#else")
    lines.append("// The deathmatch build has no game rules and no bots; the nav table")
    lines.append("// compiles to nothing rather than not compiling.")
    lines.append("#endif")

    out = "\n".join(lines) + "\n"

    if args.check:
        if not os.path.exists(OUT_PATH):
            print(f"FATAL: {os.path.relpath(OUT_PATH, ROOT)} missing; "
                  f"run scripts/build_nav.py")
            return 1
        with open(OUT_PATH) as f:
            if f.read() != out:
                print(f"FATAL: {os.path.relpath(OUT_PATH, ROOT)} is stale; "
                      f"run scripts/build_nav.py")
                return 1
        print("nav: qwtf/bots_nav.qc is fresh")
        return 0

    with open(OUT_PATH, "w") as f:
        f.write(out)
    print(f"wrote {os.path.relpath(OUT_PATH, ROOT)}: {len(routes)} routes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
