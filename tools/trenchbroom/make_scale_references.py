#!/usr/bin/env python3
"""Write tools/trenchbroom/scale-references.map -- our scale references (0308).

    python3 tools/trenchbroom/make_scale_references.py

WHY THIS IS A SCRIPT AND NOT A HAND-WRITTEN .map
--------------------------------------------------
The first version of this template was written by hand, face by face, and my own
reader (scripts/mapfile.py) came back with 14 brushes instead of the 26 written,
10 of them missing a texture, and boxes it read as RAMPS -- a staircase whose top is
horizontal reported as a 3.57 degree slope, and the 128-deep water pool as 26.57.
None of it was a parser bug: it was hand-written brush planes, which is exactly the
work Quake's tools do for you and exactly what this kit exists to stop the owner
having to do by hand.

So the geometry is emitted by `gen_map.box_brush`, the same function that writes
maps/forts.map. That makes the numbers in the template PROVABLY the numbers the checks
use, rather than numbers that look like them, and it means a fix to the reference
reaches the owner's copy.

The file is committed as well as generated, because TrenchBroom opens a .map and not a
Python script. Regenerate it and commit the result; `make_scale_references.py --check`
prints the diff and exits non-zero if the committed file is stale.
"""

import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import gen_map as g          # noqa: E402
import mapfile               # noqa: E402

OUT = os.path.join(ROOT, "tools", "trenchbroom", "scale-references.map")

WALL = g.TEX_WALL
FLOOR = g.TEX_FLOOR
BRICK = g.TEX_RED      # the duotoned castle brick; team colour is what it is FOR
LIGHT = g.TEX_CEIL
WATER = g.TEX_WATER

# The numbers, and where each one comes from. Every line here is traceable to
# something the checks already assert -- a reference sheet of numbers invented for the
# sheet is a rumour.
HULL_W, HULL_H = 32, 56            # LibreQuake's, defs.qc:362. 24 below, 32 above.
DOOR = 128                         # MIN_W is 96 INCLUDING the hull; 96 total is the
                                   # hull exactly, so it is not a margin.
STEP_RISE, STEP_TREAD, STEP_W = 16, 32, 128   # rise <= 18, tread >= 32
RAMP_RUN, RAMP_RISE, RAMP_W = 32, 8, 128      # 1:4, 14.04 degrees
RAMP_LAND = 16                         # a ramp does not start on the floor; see below
# The 30-degree ramp, next to the 1:4 one. The owner's rule is 30 or less, so the
# demonstration wants to be AT the limit without betting on it: 128 rise over 224 run
# (4:7) is 29.74 degrees -- the steepest ramp with clean numbers that stays under. Both
# numbers are multiples of 32, like everything else on this sheet.
RAMP30_RUN, RAMP30_RISE, RAMP30_W = 224, 128, 128
RAIL_H = 32                            # more than the 18 step-up, so it cannot be walked through
JUMP = 40                          # the height the checks assert you can get OUT with
WATER_D = 64                       # 48 is EXACTLY a player's height: unusable

HEADER = """// TEMPLATE .map -- our scale references, to measure against (0308).
//
// GENERATED by tools/trenchbroom/make_scale_references.py -- do not hand-edit.
// Regenerate with:  python3 tools/trenchbroom/make_scale_references.py
// Check it with:    python3 tools/trenchbroom/make_scale_references.py --check
//
// WHY THIS IS GENERATED AND NOT HAND-WRITTEN. The first version was written face by
// face and scripts/mapfile.py read it back with 14 brushes instead of the 26 written,
// 10 of them missing a texture, and boxes it reported as RAMPS -- a staircase whose top
// is horizontal came back as a 3.57 degree slope, and the 128-deep water pool as 26.57.
// None of that was a parser bug. It was hand-written brush planes, which is the work
// Quake's tools do for you and the reason this kit exists. So the ( ) below are written
// by gen_map.box_brush and gen_map.ramp_brush -- the same functions that write
// maps/forts.map -- which makes every number here PROVABLY a number the checks use.
//
// AND THE READER IS NOT ENOUGH. With the worldspawn block unclosed, mapfile.py was
// perfectly happy: it treats every { } as a brush, and a brush with no faces is skipped.
// qbsp was not:
//
//   parse_brush: scale-references.map[line 66]: Brush primitives: expected second {
//   at beginning of brush, got "classname"
//
// qbsp is the thing that will read the OWNER's map, so it gets the last word on ours:
// verify_qbsp() runs it over this file before the file is written. Comments belong
// ABOVE a block, not inside one -- qbsp refuses those too, with "Line is incomplete".
//
// WHAT IS HERE, one of each thing whose SIZE matters:
//
//   player hull   32 x 32 x 56    mins -16 -16 -24, maxs 16 16 32. NOT symmetric about
//                                  the origin, which is why a hull flush against a floor
//                                  is resting and not inside it.
//   doorway       128 x 128       two jambs 128 apart with a lintel over the gap
//   staircase     rise 16, tread 32, width 128, eight steps to a storey
//   ramp          1:4 (32 run, 8 rise), 14.04 degrees -- gentler than any of our three
//                                  real flights (28.81, 25.28, 25.11), on purpose: this
//                                  is the steepest thing that certainly works, not the
//                                  one that might
//   ramp 30 deg   128 rise over 224 run, 29.74 degrees, RAILED on both open sides --
//                                  the steepest ramp with clean numbers that stays under
//                                  the owner's limit; the two walls alongside ride the
//                                  surface 32 above it, which is more than the 18
//                                  step-up, so a player cannot walk through a rail
//
// THE OWNER'S RAMP RULE: a ramp is preferred over steps; slope 30 degrees or less; at
// least 128 wide; every open side railed, so you cannot roll off it. The 30-degree ramp
// on this sheet shows all four at once.
//   jump block    40 high         walk ONTO 40, walk OUT of 40; 56 is neither
//   water         64 deep         48 is EXACTLY a player's height, and a hull touching
//                                  ceiling and floor at once collides, so the route is
//                                  unusable
//
// THE FIVE RULES, on the geometry as drawn here:
//
//   1. doorways at least 128 x 128
//   2. steps 16 or less
//   3. no hole without a wall around it
//   4. every room has a way out on foot
//   5. the turn-in centre of the battlement is exposed to the enemy battlement
//
// Rule 4 is the one that catches people. A ledge you can fall off is a ledge you get out
// of by walking off it. A ledge you can only BE PUT ON by falling is a trap as far as
// the checks are concerned -- see .team/STATE.md, where that is currently a question
// about what the check means rather than a hole in the map.
//
// Delete what you do not need. Keep the numbers.
{
"classname" "worldspawn"
"wad" "our.wad"
"message" "scale references - not a playable map"
"light" "0"
"_ambient" "20"
"_sunlight" "220"
"_sun_mangle" "-60 -55 -45"
"_sunlight2" "55"
"_minlight" "32"

// THE BRUSHES BELOW ARE INSIDE THIS BLOCK, and that is not a style choice.
// qbsp reads a { } whose first token is not ( or { as an ENTITY, so a brush emitted
// after worldspawn closes is read as an entity and the file dies with:
//
//   parse_brush: expected second { at beginning of brush, got "classname"
//
// which is exactly what it said, and what it took three wrong probes to believe.
"""


def box(L, x0, y0, z0, x1, y1, z1, tex=WALL):
    """One box, six correct faces, from the same emitter our maps use."""
    L += g.box_brush(x0, y0, z0, x1, y1, z1, tex)


def label(L, text):
    L.append("")
    L.append(f"// {text}")
    L.append("")


def build():
    L = HEADER.split("\n")

    # ---- the player hull, at the origin of the world ------------------------
    label(L, "=== THE PLAYER: 32 x 32 x 56, the number everything else is against")
    box(L, -HULL_W // 2, -HULL_W // 2, -24, HULL_W // 2, HULL_W // 2, 32, BRICK)

    # ---- a doorway, 128 x 128 ------------------------------------------------
    y1 = 256
    label(L, "=== A DOORWAY 128 x 128: two jambs 128 apart, a lintel over the gap")
    box(L, 0, 0, 0, DOOR, y1, 256)                  # left jamb
    box(L, 2 * DOOR, 0, 0, 3 * DOOR, y1, 256)       # right jamb
    box(L, DOOR, 0, DOOR, 2 * DOOR, y1, 256)        # the lintel
    # so the opening is x 128..256 (128 wide) and z 0..128 (128 tall)
    L.append("")

    # ---- a staircase: rise 16, tread 32, width 128 --------------------------
    label(L, "=== A STAIRCASE: rise 16, tread 32, width 128. Eight steps = 128")
    sx, steps = 512, 8
    for i in range(steps):
        # step i is one tread deep and rises to (i+1)*16; the box under it is solid
        box(L, sx + i * STEP_TREAD, 0, 0,
            sx + (i + 1) * STEP_TREAD, STEP_W, (i + 1) * STEP_RISE, FLOOR)
    L.append("")

    # ---- a ramp, 1:4 ---------------------------------------------------------
    label(L, "=== A RAMP: 32 of run per 8 of rise, 1:4, 14.04 degrees, width 128")
    # ONE ramp, 256 of run and 64 of rise: 1:4, 14.04 degrees. One brush, not a stack
    # of eight slices, because that is how our three real flights are built -- their
    # runs are 512, 576 and 960 -- and because ramp_brush DEGENERATES on a short slice:
    # with 32 of run its low face collapses to a zero-length edge, mapfile.py drops that
    # face, and the brush is left with three planes and no normal. Caught by the verify()
    # below, which is the only reason this file is trustworthy.
    #
    # z_low is RAMP_LAND, not 0, so the ramp starts on a landing like ours do.
    L += g.ramp_brush(1024, 0, 0, 1024 + 8 * RAMP_RUN, RAMP_W,
                      float(RAMP_LAND), float(RAMP_LAND + 8 * RAMP_RISE),
                      FLOOR, along="x")
    L.append("")

    # ---- a 30-degree ramp, railed -------------------------------------------
    label(L, "=== A 30-DEGREE RAMP, RAILED: 128 of rise over 224 of run, 29.74")
    L.append("// degrees -- the steepest ramp with clean numbers that stays under the")
    L.append("// owner's 30-degree limit. THE OWNER'S RAMP RULE: ramps are preferred over")
    L.append("// steps; slope 30 degrees or less; at least 128 wide; every open side")
    L.append("// railed, so you cannot roll off it. The two walls alongside are the rails:")
    L.append("// their tops follow the ramp's surface 32 above it, past the 18 step-up,")
    L.append("// so a player cannot walk through them. One brush each, same emitter.")
    # The ramp itself, 128 wide, beside the 1:4 one.
    L += g.ramp_brush(1024, 192, 0, 1024 + RAMP30_RUN, 192 + RAMP30_W,
                      float(RAMP_LAND), float(RAMP_LAND + RAMP30_RISE),
                      FLOOR, along="x")
    # The rails: same slope, their tops 32 above the walking surface at every x.
    # 16 wide, which is the corridor wall thickness our own flights use.
    L += g.ramp_brush(1024, 192 - 16, 0, 1024 + RAMP30_RUN, 192,
                      float(RAMP_LAND + RAIL_H), float(RAMP_LAND + RAMP30_RISE + RAIL_H),
                      WALL, along="x")
    L += g.ramp_brush(1024, 192 + RAMP30_W, 0, 1024 + RAMP30_RUN, 192 + RAMP30_W + 16,
                      float(RAMP_LAND + RAIL_H), float(RAMP_LAND + RAMP30_RISE + RAIL_H),
                      WALL, along="x")
    L.append("")

    # ---- a 40-high jump block -----------------------------------------------
    label(L, "=== A 40-HIGH BLOCK: walk OUT of 40, not 56. The checks assert 40")
    box(L, 1536, 0, 0, 1664, 128, JUMP)
    L.append("")

    # ---- a water pool, 64 deep ----------------------------------------------
    label(L, "=== WATER 64 DEEP. 48 is EXACTLY a player's height and the route is")
    L.append("// unusable: the hull touches ceiling and floor at once and collides.")
    box(L, 1792, 0, 0, 2048, 128, WATER_D, WATER)
    L.append("")

    # ---- eight spawns, four a side ------------------------------------------
    # CLOSE worldspawn. Every brush above is inside it; the entities below are after it.
    L.append("}")

    # The light over the player box, AFTER the close. It is an entity, and an entity
    # emitted before the close is a brush qbsp cannot read -- which is the same failure
    # as the brushes themselves, one level up.
    L.append('{')
    L.append('"classname" "light"')
    L.append('"origin" "0 0 200"')
    L.append('"light" "600"')
    L.append("}")
    L.append("")

    label(L, "=== SPAWNS. Four a side is the FLOOR, not a target: M4a's done-when")
    L.append("// asks 4-6 because with few spawns PutClientInServer takes the only free")
    L.append("// spot, which is where the killer is standing. Face them inward, and give")
    L.append("// every one a distinct targetname -- the spawn check finds them by name.")
    for i in range(4):
        L.append('{')
        L.append('"classname" "info_player_deathmatch"')
        L.append(f'"origin" "2432 {64 + i * 128} 24"')
        L.append('"angle" "0"')
        L.append(f'"targetname" "spawn_{i}"')
        L.append("}")
    for i in range(4):
        L.append('{')
        L.append('"classname" "info_player_deathmatch"')
        L.append(f'"origin" "3072 {64 + i * 128} 24"')
        L.append('"angle" "180"')
        L.append(f'"targetname" "spawn_{4 + i}"')
        L.append("}")
    L.append("")

    # ---- one key and one turn-in per team ------------------------------------
    label(L, "=== ONE KEY PER TEAM. spawnflags 2 is red, 4 is blue (qwtf/ctf.qc:172).")
    L.append("// 0 is NEITHER and the map is broken while still drawing correctly in the")
    L.append("// editor, which is why qwtf.fgd spells the three values out.")
    for tx, tn, sf in ((2432, "red", 2), (3072, "blue", 4)):
        L.append('{')
        L.append('"classname" "item_qwtf_key"')
        L.append(f'"origin" "{tx} 600 40"')
        L.append(f'"spawnflags" "{sf}"')
        L.append(f'"targetname" "key_{tn}"')
        L.append("}")
    L.append("")
    label(L, "=== ONE TURN-IN PER TEAM: carry the ENEMY key here. Rule 5 -- on a")
    L.append("// battlement the enemy can see. A turn-in out of sight passes every")
    L.append("// structural check and makes the map dull.")
    for ty, tn, sf in ((256, "red", 2), (384, "blue", 4)):
        L.append('{')
        L.append('"classname" "item_qwtf_stand"')
        L.append(f'"origin" "2752 {ty} 40"')
        L.append(f'"spawnflags" "{sf}"')
        L.append(f'"targetname" "stand_{tn}"')
        L.append("}")
    L.append("")
    return "\n".join(L) + "\n"


def verify(text):
    """Read it back with our own reader and MEASURE what it claims to be.

    This is the part that caught the hand-written version, so it is not optional: a
    reference sheet whose numbers do not read back as themselves is worse than none,
    because it is trusted.
    """
    brushes = mapfile.brushes_in(text)
    unmodelled = mapfile.unmodelled(text)
    problems = []
    if unmodelled:
        problems.append(f"{len(unmodelled)} brushes are general convex shapes "
                        f"mapfile cannot model, at lines "
                        f"{[ln for ln, _b, _p in unmodelled[:4]]}")
    if any(len(b) != 7 and not mapfile.is_ramp(b) for b in brushes):
        problems.append("a brush has no texture name")

    ramps = [b for b in brushes if mapfile.is_ramp(b)]
    # the 1:4, the 30-degree, and its two rails
    if len(ramps) != 4:
        problems.append(f"4 ramps wanted (the 1:4, the 30-degree, its two rails), "
                        f"{len(ramps)} present")

    # each ramp must measure one of the two slopes the header names -- 1:4 and the
    # 29.74 of the 30-degree sheet entry -- measured off the EMITTED geometry, which
    # is the rule the rest of this repo's checks follow.
    WANTED_DEG = (14.036243467926479, 29.744881289533577)
    for b in ramps:
        sl = mapfile.slope(b)
        if sl:
            _along, _rise, _run, deg = sl
            if min(abs(deg - w) for w in WANTED_DEG) > 0.01:
                problems.append(f"a ramp measures {deg:.2f} degrees, and the header "
                                f"names 14.04 (1:4) or 29.74 (the 30-degree sheet entry)")

    ents = {}
    for cls, flags, _n in _entities(text):
        ents.setdefault(cls, []).append(flags)
    for cls, want in (("info_player_deathmatch", 8), ("item_qwtf_key", 2),
                      ("item_qwtf_stand", 2)):
        got = len(ents.get(cls, []))
        if got != want:
            problems.append(f"{want} {cls} wanted, {got} present")
    for cls in ("item_qwtf_key", "item_qwtf_stand"):
        for flags in ents.get(cls, []):
            if flags not in ("2", "4"):
                problems.append(f"a {cls} has spawnflags {flags}, which is neither "
                                f"red (2) nor blue (4)")
    names = [n for _c, _f, n in _entities(text)
             if n and n.startswith("spawn_")]
    if len(set(names)) != len(names):
        problems.append("two spawns share a targetname")

    problems += verify_qbsp(text)

    return problems, len(brushes), len(ramps)


# qbsp GETS THE LAST WORD, AND NOW THAT IT AGREES IT CAN BE ASKED
# -----------------------------------------------------------
# The first version of this file was verified with mapfile.py alone and came out green,
# and qbsp refused it:
#
#   parse_brush: scale-references.map[line 66]: Brush primitives: expected second {
#   at beginning of brush, got "classname"
#
# mapfile treats every { } as a brush and skips one with no faces, so an unclosed
# worldspawn block and an entity emitted in the wrong place are both invisible to it. An
# in-process qbsp check was written to catch that, removed because it reported failures on
# short fragments that compile fine inside a whole map, and is now back because the FILE
# is right -- 15 brushes, qbsp exit 0, 0.017s.
#
# Only qbsp, not vis: this is a sheet of reference geometry standing in open space, not a
# sealed map, so vis has nothing to do and says so ("unknown header/empty portal file"),
# which is correct and not a defect in the template. What matters here is that qbsp can
# READ the file, because that is the thing the owner's editor and the owner's compiler
# both have to be able to do.
QBSP = os.path.join(ROOT, "third_party", "ericw-tools", "build-linux", "qbsp", "qbsp")


def verify_qbsp(text):
    """qbsp must be able to READ this file. Returns a list of problems, empty is good."""
    if not os.access(QBSP, os.X_OK):
        return []                      # ericw-tools not built here; the other checks stand
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        src = os.path.join(td, "t.map")
        with open(src, "w") as f:
            f.write(text)
        r = subprocess.run([QBSP, "-wadpath", os.path.join(ROOT, "web", "id1"),
                            src, os.path.join(td, "t.bsp")],
                           capture_output=True, text=True, timeout=120)
        if r.returncode == 0:
            return []
        errs = [ln.strip() for ln in (r.stdout + r.stderr).split("\n")
                if "ERROR" in ln or ln.startswith("parse")]
        return errs[:2] or [f"qbsp refused the template (exit {r.returncode})"]


def _entities(text):
    """(classname, spawnflags, targetname) per entity block."""
    out = []
    for block in text.split("{"):
        cls = flags = name = None
        for line in block.splitlines():
            s = line.strip()
            if s.startswith('"classname"'):
                cls = s.split('"')[3]
            elif s.startswith('"spawnflags"'):
                flags = s.split('"')[3]
            elif s.startswith('"targetname"'):
                name = s.split('"')[3]
        if cls and cls != "worldspawn":
            out.append((cls, flags, name))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify the committed file instead of writing it")
    args = ap.parse_args()

    text = build()
    problems, nbrush, nramp = verify(text)
    if problems:
        print("FAIL: the generated template does not read back as itself:")
        for p in problems:
            print("  -", p)
        return 1
    print(f"ok: {nbrush} brushes, {nramp} of them ramps (the 1:4, the 30-degree, its "
          f"two rails), 8 spawns, "
          f"2 keys, 2 turn-ins, every spawnflags red or blue, no duplicate spawn name")

    if args.check:
        if not os.path.exists(OUT):
            print(f"FAIL: {OUT} does not exist")
            return 1
        cur = open(OUT).read()
        if cur != text:
            print(f"FAIL: {OUT} is stale. Regenerate:")
            print(f"  python3 tools/trenchbroom/make_scale_references.py")
            return 1
        print(f"ok: {os.path.relpath(OUT, ROOT)} is up to date")
        return 0

    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())